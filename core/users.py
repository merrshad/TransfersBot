"""User registration, roles, statuses and the ban/unban rules.

Registration is open: any user who starts the bot becomes an active ``user``
immediately. ``owner`` accounts are recognised from configuration by the
platform adapters, which pass ``role=UserRole.OWNER`` on registration.
"""

from __future__ import annotations

from collections.abc import Mapping
from dataclasses import dataclass
from datetime import UTC, datetime
from enum import Enum
from typing import Protocol, runtime_checkable

from core.errors import (
    CannotBanOwnerError,
    PermissionDeniedError,
    UserBannedError,
    UserLimitReachedError,
    UserNotFoundError,
)
from core.models import Platform
from core.ports import TransactionManager


class UserRole(str, Enum):
    """Authorisation level of a bridge user."""

    OWNER = "owner"
    USER = "user"


class UserStatus(str, Enum):
    """Whether a user may use the bridge."""

    ACTIVE = "active"
    BANNED = "banned"


@dataclass(frozen=True, slots=True)
class User:
    """A registered bridge user (one identity per platform)."""

    id: int
    platform: Platform
    platform_user_id: int
    role: UserRole
    status: UserStatus
    created_at: datetime
    last_chat_id: int | None = None
    """Chat id of the most recent private message, used as the send target.

    Telegram guarantees ``chat.id == user.id`` in private chats; Bale does not
    document that, so the actual chat id observed on the last inbound message is
    remembered and preferred over ``platform_user_id``.
    """
    public_id: str = ""
    """Short random id shown to users for ``/pair`` and owner commands."""

    @property
    def is_owner(self) -> bool:
        """Whether the user may run owner-only commands."""
        return self.role is UserRole.OWNER

    @property
    def is_banned(self) -> bool:
        """Whether the user is banned."""
        return self.status is UserStatus.BANNED

    @property
    def is_active(self) -> bool:
        """Whether the user is active (not banned)."""
        return self.status is UserStatus.ACTIVE


@dataclass(frozen=True, slots=True)
class UserStats:
    """Aggregate user counters for owner-facing reporting (no user content)."""

    total: int
    active: int
    banned: int
    owners: int


@runtime_checkable
class UserRepositoryPort(Protocol):
    """Persistence operations required by :class:`UserService`."""

    def get_by_id(self, user_id: int) -> User | None:
        """Fetch a user by internal id."""
        ...

    def get_by_public_id(self, public_id: str) -> User | None:
        """Fetch a user by the short random id shown to users."""
        ...

    def get_by_platform(self, platform: Platform, platform_user_id: int) -> User | None:
        """Fetch a user by their platform identity."""
        ...

    def create(
        self,
        *,
        platform: Platform,
        platform_user_id: int,
        role: UserRole,
        status: UserStatus,
        created_at: datetime,
        public_id: str | None = None,
    ) -> User:
        """Insert a new user and return it.

        ``public_id`` is normally generated by the repository when omitted.
        """
        ...

    def set_role(self, user_id: int, role: UserRole) -> User | None:
        """Change a user's role; ``None`` when the user does not exist."""
        ...

    def set_status(self, user_id: int, status: UserStatus) -> User | None:
        """Change a user's status; ``None`` when the user does not exist."""
        ...

    def set_last_chat_id(self, user_id: int, chat_id: int) -> User | None:
        """Remember the private chat id observed for a user."""
        ...

    def count(self) -> int:
        """Total number of registered users."""
        ...

    def count_by_status(self) -> Mapping[UserStatus, int]:
        """Registered users grouped by status (missing keys mean zero)."""
        ...

    def count_by_role(self, role: UserRole) -> int:
        """Registered users with the given role."""
        ...

    def list_recent(self, limit: int) -> tuple[User, ...]:
        """Newest users first, at most ``limit`` rows."""
        ...


class UserService:
    """Owns registration, status transitions and access checks for users.

    Args:
        users: Repository implementing :class:`UserRepositoryPort`.
        tx: Transaction manager sharing the connection with ``users``.
        max_users: Hard registration cap; ``0`` means unlimited. Owner
            registrations always bypass the cap so the bridge cannot lock the
            owner out of their own instance.
    """

    def __init__(
        self,
        users: UserRepositoryPort,
        tx: TransactionManager,
        *,
        max_users: int = 0,
    ) -> None:
        if max_users < 0:
            raise ValueError("max_users must be >= 0 (0 means unlimited).")
        self._users = users
        self._tx = tx
        self._max_users = max_users

    @property
    def max_users(self) -> int:
        """Configured registration cap (``0`` = unlimited)."""
        return self._max_users

    def get(self, user_id: int) -> User | None:
        """Return the user with ``user_id`` or ``None``."""
        return self._users.get_by_id(user_id)

    def get_by_public_id(self, public_id: str) -> User | None:
        """Return the user behind a public id, or ``None``."""
        return self._users.get_by_public_id(public_id)

    def get_by_platform(self, platform: Platform, platform_user_id: int) -> User | None:
        """Return the user behind a platform identity, or ``None``."""
        return self._users.get_by_platform(platform, platform_user_id)

    def get_or_register(
        self,
        platform: Platform,
        platform_user_id: int,
        *,
        role: UserRole = UserRole.USER,
        now: datetime | None = None,
    ) -> User:
        """Return the existing user or register a new active one.

        Calling this for a known identity is idempotent: statuses are preserved
        (a banned user stays banned) and an owner identity is promoted to
        ``owner`` without touching its status.

        Raises:
            UserLimitReachedError: When ``MAX_USERS`` is reached and the
                identity is not the owner.
        """
        with self._tx.transaction():
            existing = self._users.get_by_platform(platform, platform_user_id)
            if existing is not None:
                if role is UserRole.OWNER and not existing.is_owner:
                    promoted = self._users.set_role(existing.id, UserRole.OWNER)
                    if promoted is not None:
                        return promoted
                return existing

            if role is not UserRole.OWNER and self._max_users > 0:
                if self._users.count() >= self._max_users:
                    raise UserLimitReachedError()

            created_at = now or datetime.now(UTC)
            return self._users.create(
                platform=platform,
                platform_user_id=platform_user_id,
                role=role,
                status=UserStatus.ACTIVE,
                created_at=created_at,
            )

    def require(self, user_id: int) -> User:
        """Return a user or raise :class:`UserNotFoundError`."""
        user = self._users.get_by_id(user_id)
        if user is None:
            raise UserNotFoundError()
        return user

    def require_active(self, user_id: int) -> User:
        """Return a non-banned user or raise a domain error."""
        user = self.require(user_id)
        if user.is_banned:
            raise UserBannedError()
        return user

    def require_owner(self, actor: User) -> User:
        """Return the acting owner or raise :class:`PermissionDeniedError`."""
        if not actor.is_owner:
            raise PermissionDeniedError()
        return actor

    def count(self) -> int:
        """Number of registered users."""
        return self._users.count()

    def remember_chat(self, user_id: int, chat_id: int) -> User:
        """Remember the chat id a user is messaging the bot from.

        Called for every inbound message so system replies always go to a chat
        that is known to exist, even on platforms where the private chat id is
        not guaranteed to equal the user id.

        Raises:
            UserNotFoundError: If the user does not exist.
        """
        user = self.require(user_id)
        if user.last_chat_id == chat_id:
            return user
        with self._tx.transaction():
            updated = self._users.set_last_chat_id(user_id, chat_id)
        if updated is None:  # pragma: no cover - user existed moments ago
            raise UserNotFoundError()
        return updated

    def stats(self) -> UserStats:
        """Aggregate counters (total/active/banned/owners) for owner reports."""
        counts = self._users.count_by_status()
        return UserStats(
            total=sum(counts.values()),
            active=counts.get(UserStatus.ACTIVE, 0),
            banned=counts.get(UserStatus.BANNED, 0),
            owners=self._users.count_by_role(UserRole.OWNER),
        )

    def list_users(self, limit: int = 50) -> tuple[User, ...]:
        """Return the newest ``limit`` users (owner-facing listing).

        Raises:
            ValueError: If ``limit`` is not positive.
        """
        if limit < 1:
            raise ValueError("limit must be >= 1")
        return self._users.list_recent(limit)

    def ban(self, actor: User, target_id: int) -> User:
        """Ban ``target_id`` on behalf of an owner.

        Banning is idempotent. Owner accounts can never be banned.

        Raises:
            PermissionDeniedError: If ``actor`` is not an owner.
            UserNotFoundError: If the target does not exist.
            CannotBanOwnerError: If the target is an owner account.
        """
        self.require_owner(actor)
        with self._tx.transaction():
            target = self.require(target_id)
            if target.is_owner:
                raise CannotBanOwnerError()
            if target.is_banned:
                return target
            updated = self._users.set_status(target_id, UserStatus.BANNED)
        if updated is None:  # pragma: no cover - guarded by require() above
            raise UserNotFoundError()
        return updated

    def unban(self, actor: User, target_id: int) -> User:
        """Lift a ban on behalf of an owner (idempotent)."""
        self.require_owner(actor)
        with self._tx.transaction():
            target = self.require(target_id)
            if target.is_active:
                return target
            updated = self._users.set_status(target_id, UserStatus.ACTIVE)
        if updated is None:  # pragma: no cover - guarded by require() above
            raise UserNotFoundError()
        return updated
